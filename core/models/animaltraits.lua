end

function AnimalTraits.isValid(traitName, slotIndex)
    local options = AnimalTraits.getDropdownOptions(slotIndex)

    for _, validTrait in ipairs(options) do
        if validTrait == traitName then
            return true
        end
    end

    return false
end


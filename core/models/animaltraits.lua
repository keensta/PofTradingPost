function AnimalTraits.getDropdownOptions(slotIndex)
    if slotIndex == 1 then return AnimalTraits.Slot1 end
    if slotIndex == 2 then return AnimalTraits.Slot2 end
    if slotIndex == 3 then return AnimalTraits.Slot3 end
